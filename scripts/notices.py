#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md: the crates linked into the plugin and app (from `cargo metadata`), plus vendored code and fonts.

    python3 scripts/notices.py           # rewrite the file
    python3 scripts/notices.py --check   # fail if it is out of date
"""
import json
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "THIRD_PARTY_NOTICES.md")

EXTRA = [
    ("Signalsmith Stretch (vendor/signalsmith-stretch)", "MIT", "https://github.com/Signalsmith-Audio/signalsmith-stretch"),
    ("baseview, patched (vendor/baseview)", "MIT OR Apache-2.0", "https://github.com/RustAudio/baseview"),
    ("Liberation Sans (assets/ui/Fonts)", "OFL-1.1", "https://github.com/liberationfonts/liberation-fonts"),
]


def rows():
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "aarch64-apple-darwin"], cwd=ROOT))
    pk = {p["id"]: p for p in meta["packages"]}
    # The dreist-* crates (dreist-commons) are this project's own code.
    ws = set(meta["workspace_members"])
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    stack = [i for i in ws if pk[i]["name"] in ("dreist-plugin",)]
    seen = set()
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    return sorted({(pk[i]["name"], pk[i]["version"], pk[i]["license"] or "see repository", pk[i].get("repository") or "") for i in seen if i not in ws and not pk[i]["name"].startswith("dreist-")})


def render():
    out = ["# Third-party notices", "",
           "Dreist's binaries include the following third-party code and assets. Each is used under",
           "the licence named; the full texts are in the linked repositories and in each crate's source.",
           "Generated by `scripts/notices.py`.", "",
           "## Vendored code and fonts", "", "| Component | Licence | Source |", "| --- | --- | --- |"]
    out += [f"| {n} | {l} | {u} |" for n, l, u in EXTRA]
    out += ["", "## Rust crates", "", "| Crate | Version | Licence | Source |", "| --- | --- | --- | --- |"]
    out += [f"| {n} | {v} | {l} | {u} |" for n, v, l, u in rows()]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            print("THIRD_PARTY_NOTICES.md is out of date: run scripts/notices.py")
            sys.exit(1)
    else:
        open(OUT, "w").write(text)
