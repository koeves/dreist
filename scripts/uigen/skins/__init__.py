"""Dreist's skin layouts: a small layout language and the XML writer.

Every `.skin` under assets/ui/Skin is generated from the panel modules
next to this file (`fx.py`, `transmod.py`, ...).  A panel is a tree of
`N` nodes: a control class, an optional name (the editor finds controls
by name), a rect relative to the parent, a `pin` saying which parent
edges the control follows when the parent resizes, and any other skin
attributes.  `pin` letters: l/r/t/b stick to that edge (l+r stretches),
c centres horizontally, m centres vertically.

The writer turns pins into the ARLeft/ARTop/ARRight/ARBottom anchors the
GUI reads (dreist_gui::ctrl::Anchor), so rects and anchors can't drift
apart.
"""

from xml.sax.saxutils import quoteattr


class N:
    def __init__(self, cls, name=None, rect=(0, 0, 0, 0), pin="", kids=(), **attrs):
        self.cls = cls if cls.startswith("Ctrl") else "Ctrl" + cls
        self.name = name
        self.rect = tuple(int(round(v)) for v in rect)
        self.pin = pin
        self.kids = list(kids)
        self.attrs = attrs

    def add(self, *kids):
        self.kids.extend(kids)
        return self

    @property
    def w(self):
        return self.rect[2]

    @property
    def h(self):
        return self.rect[3]


def _fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return f"{v:.4f}"
    return str(v)


def anchors(pin, rect, pw, ph):
    """ARLeft/ARTop/ARRight/ARBottom for `pin` given the parent size."""
    x, y, w, h = rect
    out = {}

    def axis(near, far, mid, pos, size, extent, kn, kf):
        if mid:
            out[kn] = "Center 0.0000"
        elif near and far:
            out[kn] = f"FNear {pos:.4f}"
            out[kf] = f"FNear {extent - pos - size:.4f}"
        elif near:
            out[kn] = f"FNear {pos:.4f}"
        elif far:
            out[kn] = f"FFar {extent - pos:.4f}"
            out[kf] = f"FFar {size:.4f}"

    axis("l" in pin, "r" in pin, "c" in pin, x, w, pw, "ARLeft", "ARRight")
    axis("t" in pin, "b" in pin, "m" in pin, y, h, ph, "ARTop", "ARBottom")
    return out


def _emit(n, pw, ph, depth, out):
    a = {}
    if n.name:
        a["name"] = n.name
    a["rect"] = ", ".join(str(v) for v in n.rect)
    a.update(anchors(n.pin, n.rect, pw, ph))
    for k in sorted(n.attrs):
        if n.attrs[k] is None:
            a.pop(k, None)
        else:
            a[k] = _fmt(n.attrs[k])
    pad = "    " * depth
    head = pad + "<" + n.cls + "".join(f" {k}={quoteattr(v)}" for k, v in a.items())
    if not n.kids:
        out.append(head + " />")
        return
    out.append(head + ">")
    for k in n.kids:
        _emit(k, n.w, n.h, depth + 1, out)
    out.append(pad + f"</{n.cls}>")


def skin(*roots):
    """The `.skin` file for these top-level controls."""
    out = ["<!-- Generated by scripts/uigen (skins). Edit the generator, not this file. -->", "<root>"]
    for r in roots:
        _emit(r, r.w, r.h, 1, out)
    out.append("</root>")
    return ("\n".join(out) + "\n").encode()


# Layout helpers ---------------------------------------------------------

def spread(n, size, extent, margin=0):
    """Start positions of `n` items of `size` spaced evenly across
    `extent` (equal gaps between items and at both ends, after `margin`)."""
    if n <= 0:
        return []
    free = extent - 2 * margin - n * size
    gap = free / (n + 1)
    return [round(margin + gap + i * (size + gap)) for i in range(n)]


def row(items, x, y, gap):
    """Lay `items` (N nodes, sizes set) left to right from (x, y)."""
    for it in items:
        it.rect = (x, y, it.w, it.h)
        x += it.w + gap
    return items


def total_w(items, gap):
    return sum(i.w for i in items) + gap * max(len(items) - 1, 0)


PANELS = ["fx", "transmod", "effects", "mixer", "pages", "browser", "patterns", "paded", "layer", "root", "dialogs"]


def outputs():
    """Every generated skin, keyed by its path under assets/ui."""
    import importlib

    files = {}
    for m in PANELS:
        files.update(importlib.import_module(f"{__name__}.{m}").outputs())
    return files
